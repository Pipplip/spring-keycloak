import { existsSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const generatedClient = fileURLToPath(
  new URL(
    '../build/generated/openapi/typescript-angular/api/catalogue.service.ts',
    import.meta.url,
  ),
);
const backendDirectory = fileURLToPath(new URL('../../backend/', import.meta.url));

if (process.env.SKIP_API_GENERATION === 'true') {
  if (!existsSync(generatedClient)) {
    console.error('The generated API client is missing; start the backend Compose service first.');
    process.exitCode = 1;
  } else {
    console.log('Using the Angular API client generated by the backend service.');
  }
} else {
  const gradleCommand = process.platform === 'win32' ? 'gradlew.bat' : './gradlew';
  const result = spawnSync(gradleCommand, ['validateAngularOpenApiOutput'], {
    cwd: backendDirectory,
    shell: process.platform === 'win32',
    stdio: 'inherit',
  });

  if (result.error) {
    console.error(
      'Unable to run the Gradle wrapper to generate the Angular API client.',
      result.error,
    );
    process.exitCode = 1;
  } else if (result.status !== 0) {
    console.error(
      `Angular API client generation failed with exit code ${result.status ?? 'unknown'}.`,
    );
    process.exitCode = result.status ?? 1;
  }
}
